// The manifesto (/manifesto, after manifesto.blandina.org) is built in apps/manifesto, the single source.
// This copies its css/js/assets to public/manifesto and writes the page markup (everything inside <body>,
// asset paths rewritten to /manifesto/assets/) to app/manifesto/manifesto.generated.ts.
// Runs before `dev` and `build`. Edit apps/manifesto only; the outputs are overwritten every run.
import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const src = resolve("..", "manifesto");
const dest = resolve("public", "manifesto");
const generated = resolve("app", "manifesto", "manifesto.generated.ts");

if (!(await stat(src).catch(() => null))) {
  console.warn(`[sync-manifesto] ${src} not found, skipping.`);
  process.exit(0);
}

await rm(dest, { recursive: true, force: true });
for (const dir of ["css", "js", "assets"]) await cp(resolve(src, dir), resolve(dest, dir), { recursive: true });

const html = await readFile(resolve(src, "index.html"), "utf8");
const open = html.indexOf(">", html.indexOf("<body")) + 1;
const close = html.indexOf("<script", open);
if (open <= 0 || close < 0) throw new Error("[sync-manifesto] could not find <body> content");
const markup = html
  .slice(open, close)
  .replace(/\b(src|srcset|poster)="assets\//g, '$1="/manifesto/assets/')
  .replace(/\n\s*\n/g, "\n")
  .trim();

await mkdir(resolve(generated, ".."), { recursive: true });
await writeFile(
  generated,
  `// GENERATED by scripts/sync-manifesto.mjs from apps/manifesto/index.html. Do not edit.\n` +
    `export const MANIFESTO_HTML = ${JSON.stringify(markup)};\n`,
);
console.log(`[sync-manifesto] public/manifesto + app/manifesto/manifesto.generated.ts (${markup.length} chars)`);
